namespace EDV.Framework.Eventing.Abstractions;

/// <summary>
/// Устанавливает контекст арендатора для времени выполнения диспетчеризации интеграционного события,
/// чтобы обработчики — и их арендатор-фильтрованные DbContexts — видели правильный арендатор,
/// даже когда событие публикуется из фоновой области (диспетчер outbox, фоновые сервисы,
/// периодические задания), которая не имеет HTTP-запроса и, следовательно, контекста арендатора.
///
/// Контекст арендатора ДОЛЖЕН быть установлен <b>до</b> разрешения обработчиков:
/// <c>MultiTenantDbContext</c> захватывает свой <c>TenantInfo</c> во время создания,
/// поэтому установка арендатора после материализации обработчика (и его DbContext)
/// слишком запоздала и оставляет фильтр запросов по арендатору с разыменованием null-арендатора.
///
/// Реализация по умолчанию (<c>NullEventTenantScope</c>) ничего не делает;
/// композиция мультиарендности регистрирует реализацию на основе Finbuckle.
/// Нахождение абстракции здесь позволяет шине событий оставаться независимой
/// от технологии мультиарендности.
/// </summary>
public interface IEventTenantScope
{
    /// <summary>
    /// Начинает область арендатора для <paramref name="tenantId"/>. Освобождение
    /// возвращаемого дескриптора восстанавливает предыдущего фонового арендатора.
    /// null/пустой идентификатор оставляет фоновый контекст неизменным
    /// (глобальные события, не привязанные к арендатору).
    /// </summary>
    IDisposable Begin(string? tenantId);
}