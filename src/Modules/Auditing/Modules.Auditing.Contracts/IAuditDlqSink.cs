namespace EDV.Modules.Auditing.Contracts;

/// <summary>
/// Запасной приёмник для пакетов аудита, которые основной sink не смог сохранить.
/// Реализации должны быть надёжными и самодостаточными — DLQ является последним
/// рубежом защиты, поэтому не может разделять инфраструктуру с основным sink
/// (например, не отправляйте SQL DLQ в тот же Postgres, который только что упал).
/// Рекомендуемые цели: локальный JSONL-файл с ежедневной ротацией или очередь
/// с гарантией доставки at-least-once.
/// </summary>
public interface IAuditDlqSink
{
    /// <summary>
    /// Сохраняет пакет, исчерпавший все повторы основного sink. Реализация DLQ
    /// не должна выбрасывать исключения никогда — логировать сбой и отбрасывать
    /// данные перед тем, как поднять исключение выше, так как конвейеру аудита
    /// больше некуда эскалировать.
    /// </summary>
    Task WriteAsync(IReadOnlyList<AuditEnvelope> batch, CancellationToken ct);
}
